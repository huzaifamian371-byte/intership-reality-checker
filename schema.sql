-- ----------------------------------------------------------------------------
-- 1. USERS
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    user_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR2(255) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    full_name     VARCHAR2(150) NOT NULL,
    role          VARCHAR2(20) DEFAULT 'student' NOT NULL,
    is_active     NUMBER(1) DEFAULT 1 NOT NULL,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_role CHECK (role IN ('student', 'admin')),
    CONSTRAINT chk_users_active CHECK (is_active IN (0, 1))
);

CREATE INDEX idx_users_email ON USERS (email);
CREATE INDEX idx_users_role ON USERS (role);

-- ----------------------------------------------------------------------------
-- 2. STUDENT_PROFILES
-- ----------------------------------------------------------------------------
CREATE TABLE STUDENT_PROFILES (
    profile_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          NUMBER NOT NULL,
    university       VARCHAR2(200),
    degree           VARCHAR2(200),
    graduation_year  NUMBER(4),
    graduation_date  DATE,
    gpa              NUMBER(3, 2),
    bio              VARCHAR2(1000),
    cv_filename      VARCHAR2(255),
    cv_uploaded_at   TIMESTAMP,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_student_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_profiles_user FOREIGN KEY (user_id) REFERENCES USERS (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_profiles_gpa CHECK (gpa IS NULL OR (gpa >= 0.00 AND gpa <= 4.00))
);

CREATE INDEX idx_profiles_user ON STUDENT_PROFILES (user_id);

-- ----------------------------------------------------------------------------
-- 3. SKILLS (Master skills dictionary)
-- ----------------------------------------------------------------------------
CREATE TABLE SKILLS (
    skill_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR2(100) NOT NULL,
    category    VARCHAR2(50) NOT NULL,
    description VARCHAR2(255),
    CONSTRAINT uq_skills_name UNIQUE (name),
    CONSTRAINT chk_skills_category CHECK (category IN ('programming', 'web', 'data', 'cloud', 'soft_skills', 'tools'))
);

CREATE INDEX idx_skills_category ON SKILLS (category);
CREATE INDEX idx_skills_name ON SKILLS (name);

-- ----------------------------------------------------------------------------
-- 4. STUDENT_SKILLS (Student skill mapping)
-- ----------------------------------------------------------------------------
CREATE TABLE STUDENT_SKILLS (
    student_skill_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          NUMBER NOT NULL,
    skill_id         NUMBER NOT NULL,
    proficiency      VARCHAR2(20) NOT NULL,
    verified         NUMBER(1) DEFAULT 0 NOT NULL,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_student_skill UNIQUE (user_id, skill_id),
    CONSTRAINT fk_student_skills_user FOREIGN KEY (user_id) REFERENCES USERS (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_student_skills_skill FOREIGN KEY (skill_id) REFERENCES SKILLS (skill_id) ON DELETE CASCADE,
    CONSTRAINT chk_student_skills_prof CHECK (proficiency IN ('Beginner', 'Intermediate', 'Advanced')),
    CONSTRAINT chk_student_skills_ver CHECK (verified IN (0, 1))
);

CREATE INDEX idx_std_skills_user ON STUDENT_SKILLS (user_id);
CREATE INDEX idx_std_skills_skill ON STUDENT_SKILLS (skill_id);

-- ----------------------------------------------------------------------------
-- 5. PROJECTS (Student showcase portfolio projects)
-- ----------------------------------------------------------------------------
CREATE TABLE PROJECTS (
    project_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      NUMBER NOT NULL,
    title        VARCHAR2(200) NOT NULL,
    description  CLOB,
    tech_used    VARCHAR2(500),
    project_url  VARCHAR2(500),
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_projects_user FOREIGN KEY (user_id) REFERENCES USERS (user_id) ON DELETE CASCADE
);

CREATE INDEX idx_projects_user ON PROJECTS (user_id);

-- ----------------------------------------------------------------------------
-- 6. JOBS (Raw job descriptions and parsed metadata)
-- ----------------------------------------------------------------------------
CREATE TABLE JOBS (
    job_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             NUMBER,
    title               VARCHAR2(255) NOT NULL,
    company             VARCHAR2(255),
    location            VARCHAR2(200),
    work_type           VARCHAR2(50) DEFAULT 'onsite' NOT NULL,
    duration            VARCHAR2(100),
    stipend             VARCHAR2(150),
    raw_text            CLOB NOT NULL,
    role_summary        CLOB,
    experience_required VARCHAR2(255),
    education_required  VARCHAR2(255),
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_jobs_user FOREIGN KEY (user_id) REFERENCES USERS (user_id) ON DELETE SET NULL,
    CONSTRAINT chk_jobs_work_type CHECK (work_type IN ('onsite', 'remote', 'hybrid', 'unspecified'))
);

CREATE INDEX idx_jobs_user ON JOBS (user_id);
CREATE INDEX idx_jobs_created ON JOBS (created_at);

-- ----------------------------------------------------------------------------
-- 7. JOB_REQUIREMENTS (Normalized skills extracted from jobs)
-- ----------------------------------------------------------------------------
CREATE TABLE JOB_REQUIREMENTS (
    req_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id     NUMBER NOT NULL,
    skill_name VARCHAR2(100) NOT NULL,
    req_type   VARCHAR2(20) DEFAULT 'required' NOT NULL,
    importance VARCHAR2(20) DEFAULT 'critical' NOT NULL,
    CONSTRAINT fk_job_reqs_job FOREIGN KEY (job_id) REFERENCES JOBS (job_id) ON DELETE CASCADE,
    CONSTRAINT chk_job_reqs_type CHECK (req_type IN ('required', 'preferred', 'other')),
    CONSTRAINT chk_job_reqs_imp CHECK (importance IN ('critical', 'nice_to_have', 'neutral'))
);

CREATE INDEX idx_job_reqs_job ON JOB_REQUIREMENTS (job_id);

-- ----------------------------------------------------------------------------
-- 8. JOB_ANALYSIS (Structured AI analysis output, risks, and match scores)
-- ----------------------------------------------------------------------------
CREATE TABLE JOB_ANALYSIS (
    analysis_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id           NUMBER NOT NULL,
    user_id          NUMBER NOT NULL,
    structured_json  CLOB,
    risk_score       NUMBER(3, 1),
    risk_level       VARCHAR2(20) DEFAULT 'Safe',
    risk_summary     CLOB,
    match_percentage NUMBER(5, 2),
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_job_analysis_job UNIQUE (job_id),
    CONSTRAINT fk_job_analysis_job FOREIGN KEY (job_id) REFERENCES JOBS (job_id) ON DELETE CASCADE,
    CONSTRAINT fk_job_analysis_user FOREIGN KEY (user_id) REFERENCES USERS (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_job_analysis_json CHECK (structured_json IS NULL OR structured_json IS JSON),
    CONSTRAINT chk_job_risk_lvl CHECK (risk_level IN ('Safe', 'Low', 'Medium', 'High'))
);

CREATE INDEX idx_analysis_job ON JOB_ANALYSIS (job_id);
CREATE INDEX idx_analysis_user ON JOB_ANALYSIS (user_id);

-- ----------------------------------------------------------------------------
-- 9. APPLICATIONS (Internship tracking Kanban pipeline)
-- ----------------------------------------------------------------------------
CREATE TABLE APPLICATIONS (
    application_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          NUMBER NOT NULL,
    job_id           NUMBER,
    company_name     VARCHAR2(255) NOT NULL,
    role_title       VARCHAR2(255) NOT NULL,
    status           VARCHAR2(30) DEFAULT 'Saved' NOT NULL,
    application_date DATE,
    deadline         DATE,
    notes            CLOB,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_apps_user FOREIGN KEY (user_id) REFERENCES USERS (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_apps_job FOREIGN KEY (job_id) REFERENCES JOBS (job_id) ON DELETE SET NULL,
    CONSTRAINT chk_apps_status CHECK (status IN ('Saved', 'Applied', 'Interview', 'Offer', 'Closed'))
);

CREATE INDEX idx_apps_user ON APPLICATIONS (user_id);
CREATE INDEX idx_apps_status ON APPLICATIONS (status);
CREATE INDEX idx_apps_deadline ON APPLICATIONS (deadline);

-- ----------------------------------------------------------------------------
-- 10. CV_ANALYSIS (AI CV evaluation, breakdown, and suggestions)
-- ----------------------------------------------------------------------------
CREATE TABLE CV_ANALYSIS (
    cv_analysis_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          NUMBER NOT NULL,
    job_id           NUMBER,
    raw_cv_text      CLOB,
    extracted_data   CLOB,
    cv_score         NUMBER(3),
    score_breakdown  CLOB,
    suggestions      CLOB,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_cv_user FOREIGN KEY (user_id) REFERENCES USERS (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_cv_job FOREIGN KEY (job_id) REFERENCES JOBS (job_id) ON DELETE SET NULL,
    CONSTRAINT chk_cv_data_json CHECK (extracted_data IS NULL OR extracted_data IS JSON),
    CONSTRAINT chk_cv_score_json CHECK (score_breakdown IS NULL OR score_breakdown IS JSON),
    CONSTRAINT chk_cv_sugg_json CHECK (suggestions IS NULL OR suggestions IS JSON)
);

CREATE INDEX idx_cv_user ON CV_ANALYSIS (user_id);

-- ----------------------------------------------------------------------------
-- 11. INTERVIEW_SESSIONS (Mock interview parent sessions)
-- ----------------------------------------------------------------------------
CREATE TABLE INTERVIEW_SESSIONS (
    session_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                NUMBER NOT NULL,
    job_id                 NUMBER,
    interview_type         VARCHAR2(30) DEFAULT 'mixed' NOT NULL,
    total_questions        NUMBER(2) DEFAULT 5 NOT NULL,
    current_question_index NUMBER(2) DEFAULT 0 NOT NULL,
    overall_score          NUMBER(3, 1),
    overall_feedback       CLOB,
    status                 VARCHAR2(20) DEFAULT 'in_progress' NOT NULL,
    created_at             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_interview_user FOREIGN KEY (user_id) REFERENCES USERS (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_job FOREIGN KEY (job_id) REFERENCES JOBS (job_id) ON DELETE SET NULL,
    CONSTRAINT chk_interview_type CHECK (interview_type IN ('technical', 'behavioral', 'mixed')),
    CONSTRAINT chk_interview_status CHECK (status IN ('in_progress', 'completed', 'abandoned'))
);

CREATE INDEX idx_interview_user ON INTERVIEW_SESSIONS (user_id);
CREATE INDEX idx_interview_status ON INTERVIEW_SESSIONS (status);

-- ----------------------------------------------------------------------------
-- 12. INTERVIEW_MESSAGES (Per-turn mock interview questions, answers, and coaching)
-- ----------------------------------------------------------------------------
CREATE TABLE INTERVIEW_MESSAGES (
    message_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      NUMBER NOT NULL,
    question_number NUMBER(2) NOT NULL,
    question_text   CLOB NOT NULL,
    student_answer  CLOB,
    score           NUMBER(2),
    strengths       CLOB,
    improvements    CLOB,
    sample_answer   CLOB,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_interview_msg_sess FOREIGN KEY (session_id) REFERENCES INTERVIEW_SESSIONS (session_id) ON DELETE CASCADE
);

CREATE INDEX idx_int_msg_session ON INTERVIEW_MESSAGES (session_id);

-- ----------------------------------------------------------------------------
-- 13. ROADMAPS (Dynamic personalized weekly learning plans)
-- ----------------------------------------------------------------------------
CREATE TABLE ROADMAPS (
    roadmap_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          NUMBER NOT NULL,
    job_id           NUMBER,
    total_weeks      NUMBER(2) NOT NULL,
    hours_per_week   NUMBER(2) NOT NULL,
    roadmap_data     CLOB,
    completed_topics CLOB,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_roadmaps_user FOREIGN KEY (user_id) REFERENCES USERS (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_roadmaps_job FOREIGN KEY (job_id) REFERENCES JOBS (job_id) ON DELETE SET NULL,
    CONSTRAINT chk_roadmap_data_json CHECK (roadmap_data IS NULL OR roadmap_data IS JSON),
    CONSTRAINT chk_roadmap_comp_json CHECK (completed_topics IS NULL OR completed_topics IS JSON)
);

CREATE INDEX idx_roadmaps_user ON ROADMAPS (user_id);

-- ----------------------------------------------------------------------------
-- 14. GENERATED_DOCUMENTS (Cover letters, emails, prep docs)
-- ----------------------------------------------------------------------------
CREATE TABLE GENERATED_DOCUMENTS (
    doc_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    NUMBER NOT NULL,
    job_id     NUMBER,
    doc_type   VARCHAR2(30) NOT NULL,
    tone       VARCHAR2(30) DEFAULT 'formal' NOT NULL,
    content    CLOB NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_gen_docs_user FOREIGN KEY (user_id) REFERENCES USERS (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_gen_docs_job FOREIGN KEY (job_id) REFERENCES JOBS (job_id) ON DELETE SET NULL,
    CONSTRAINT chk_gen_doc_type CHECK (doc_type IN ('cover_letter', 'email', 'interview_prep')),
    CONSTRAINT chk_gen_doc_tone CHECK (tone IN ('formal', 'friendly', 'confident'))
);

CREATE INDEX idx_gen_docs_user ON GENERATED_DOCUMENTS (user_id);

-- ----------------------------------------------------------------------------
-- 15. REPORTED_POSTINGS (Suspicious/fraudulent job postings for admin review)
-- ----------------------------------------------------------------------------
CREATE TABLE REPORTED_POSTINGS (
    report_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     NUMBER NOT NULL,
    job_id      NUMBER,
    reason      VARCHAR2(500) NOT NULL,
    details     CLOB,
    status      VARCHAR2(20) DEFAULT 'pending' NOT NULL,
    reviewed_by NUMBER,
    reviewed_at TIMESTAMP,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_reports_user FOREIGN KEY (user_id) REFERENCES USERS (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_reports_job FOREIGN KEY (job_id) REFERENCES JOBS (job_id) ON DELETE SET NULL,
    CONSTRAINT fk_reports_reviewer FOREIGN KEY (reviewed_by) REFERENCES USERS (user_id) ON DELETE SET NULL,
    CONSTRAINT chk_reports_status CHECK (status IN ('pending', 'reviewed', 'dismissed'))
);

CREATE INDEX idx_reports_user ON REPORTED_POSTINGS (user_id);
CREATE INDEX idx_reports_status ON REPORTED_POSTINGS (status);
